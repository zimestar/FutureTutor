// --- Assembly ----------------------------------------------------------------

export function Module00({ locale, shotFrames }: Module00Props) {
  let from = 0;
  return (
    <AbsoluteFill style={{ background: brand.offWhite }}>
      {MODULE00_SHOTS.map((shot, index) => {
        const duration = shotFrames[index] ?? 90;
        const start = from;
        from += duration;
        const audioSrc = audioPath(locale, shot.id);
        const text = shot.text[locale];
        const darkShot = shot.id === "04-commitments" || shot.id === "07-format";
        const scene = (() => {
          switch (shot.id) {
            case "01-welcome":
              return <ShotWelcome locale={locale} audioSrc={audioSrc} />;
            case "02-mission":
              return <ShotMission audioSrc={audioSrc} durationInFrames={duration} />;
            case "03-marketplace":
              return <ShotMarketplace locale={locale} durationInFrames={duration} />;
            case "04-commitments":
              return <ShotCommitments locale={locale} durationInFrames={duration} />;
            case "05-independent":
              return <ShotIndependent locale={locale} audioSrc={audioSrc} durationInFrames={duration} />;
            case "06-path":
              return <ShotPath locale={locale} durationInFrames={duration} />;
            case "07-format":
              return <ShotFormat locale={locale} durationInFrames={duration} />;
            default:
              return <ShotGo locale={locale} audioSrc={audioSrc} />;
          }
        })();
        return (
          <Sequence key={shot.id} from={start} durationInFrames={duration} name={shot.id}>
            {scene}
            <Audio src={staticFile(audioSrc)} />
            <Subtitles text={text} durationInFrames={duration - PAUSE_FRAMES} dark={darkShot} />
          </Sequence>
        );
      })}
    </AbsoluteFill>
  );
}
