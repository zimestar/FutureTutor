function ShotPath({ locale, durationInFrames }: { locale: Locale; durationInFrames: number }) {
  const t = LABELS[locale];
  const frame = useCurrentFrame();
  const steps = [
    { label: t.documents, icon: <FileCheck2 size={56} /> },
    { label: t.training, icon: <GraduationCap size={56} /> },
    { label: t.exam, icon: <ClipboardCheck size={56} /> },
    { label: t.interview, icon: <Video size={56} /> },
    { label: t.approval, icon: <BadgeCheck size={56} /> },
  ];
  const progress = interpolate(frame, [10, durationInFrames * 0.85], [0, 1], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
  const pulse = 1 + Math.sin(frame / 5) * 0.06;
  return (
    <AbsoluteFill style={{ background: brand.offWhite }}>
      <Watermark dark={false} />
      <div style={{ position: "absolute", left: 220, right: 220, top: 470, height: 10, borderRadius: 5, background: "#E2E8F0" }}>
        <div style={{ width: `${progress * 100}%`, height: "100%", borderRadius: 5, background: brand.blue }} />
      </div>
      <div style={{ position: "absolute", left: 140, right: 140, top: 360, display: "flex", justifyContent: "space-between" }}>
        {steps.map((step, index) => {
          const done = index === 0;
          const current = index === 1;
          const reached = progress >= index / (steps.length - 1);
          return (
            <div key={step.label} style={{ width: 280, display: "flex", flexDirection: "column", alignItems: "center", gap: 22 }}>
              <div
                style={{
                  width: 220,
                  height: 220,
                  borderRadius: 110,
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "center",
                  background: done ? brand.mint : current ? brand.blue : reached ? "#DBEAFE" : "white",
                  color: done || current ? "white" : brand.blue,
                  border: `4px solid ${done ? brand.mint : brand.blue}`,
                  transform: `scale(${current ? pulse : 1})`,
                  boxShadow: current ? "0 18px 48px rgba(37,99,235,0.35)" : "none",
                }}
              >
                {done ? <CheckCircle2 size={72} /> : step.icon}
              </div>
              <div style={{ fontFamily: brand.fontFamily, fontSize: 32, fontWeight: 800, color: brand.navy, textAlign: "center" }}>{step.label}</div>
            </div>
          );
        })}
      </div>
    </AbsoluteFill>
  );
}

