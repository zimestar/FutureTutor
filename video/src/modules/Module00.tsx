export type Module00Props = {
  locale: Locale;
  shotFrames: number[];
};

const FPS = 30;
const PAUSE_FRAMES = 12;
const audioPath = (locale: Locale, shotId: string) => `audio/module00/${locale}/${shotId}.mp3`;

export const calculateModule00Metadata: CalculateMetadataFunction<Module00Props> = async ({ props }) => {
  const shotFrames = await Promise.all(
    MODULE00_SHOTS.map(async (shot) => {
      const audio = await getAudioData(staticFile(audioPath(props.locale, shot.id)));
      return Math.ceil(audio.durationInSeconds * FPS) + PAUSE_FRAMES;
    })
  );
  return { durationInFrames: shotFrames.reduce((sum, frames) => sum + frames, 0), props: { ...props, shotFrames } };
};

