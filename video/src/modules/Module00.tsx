function ShotIndependent({ locale, audioSrc, durationInFrames }: { locale: Locale; audioSrc: string; durationInFrames: number }) {
  const t = LABELS[locale];
  const frame = useCurrentFrame();
  const days = ["L", "M", "M", "J", "V", "S", "D"];
  const accepted = frame > durationInFrames * 0.7;
  return (
    <AbsoluteFill style={{ background: brand.offWhite }}>
      <Watermark dark={false} />
      <div style={{ position: "absolute", left: 160, top: 200, width: 880, padding: 40, borderRadius: 36, background: "white", boxShadow: "0 18px 48px rgba(13,27,42,0.10)" }}>
        <div style={{ display: "flex", alignItems: "center", gap: 16, color: brand.blue, fontFamily: brand.fontFamily, fontSize: 34, fontWeight: 800 }}>
          <CalendarCheck size={44} /> {t.available}
        </div>
        <div style={{ marginTop: 28, display: "grid", gridTemplateColumns: "repeat(7, 1fr)", gap: 14 }}>
          {days.map((day, column) =>
            [0, 1, 2].map((row) => {
              const on = (column + row) % 3 !== 1;
              const appear = interpolate(frame, [10 + (column * 3 + row) * 3, 18 + (column * 3 + row) * 3], [0, 1], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
              return (
                <div
                  key={`${column}-${row}`}
                  style={{ gridColumn: column + 1, gridRow: row + 1, height: 70, borderRadius: 14, background: on ? `rgba(16,185,129,${0.2 + appear * 0.8})` : brand.offWhite, border: `2px solid ${on ? brand.mint : "#E2E8F0"}`, color: "white", fontFamily: brand.fontFamily, fontSize: 26, fontWeight: 700, display: "flex", alignItems: "center", justifyContent: "center" }}
                >
                  {row === 0 ? day : ""}
                </div>
              );
            })
          )}
        </div>
        <div style={{ marginTop: 34, display: "flex", gap: 20 }}>
          <Pill icon={<CheckCircle2 size={34} />} label={t.accept} color={brand.mint} active={accepted} />
          <Pill icon={<XCircle size={34} />} label={t.decline} color={brand.slate} active={false} />
        </div>
      </div>
      <AlexPanel audioSrc={audioSrc} />
    </AbsoluteFill>
  );
}

